const SHAPES = new Map();
function glyphShape(char) {
  const key = GLYPHS[char] ? char : '?';
  if (SHAPES.has(key)) return SHAPES.get(key);
  const rows = GLYPHS[key];
  const cells = [];
  for(let y=0;y<7;y++)for(let x=0;x<5;x++)if(rows[y][x]==='1'){
    cells.push('M'+x+' '+y+'h1v1h-1z');
  }
  const shape=cells.join('');
  SHAPES.set(key,shape);
  return shape;
}
export function vectorWidth(value, pixel=7, tracking=2){
  const n=String(value ?? '').length;
  return n>0 ? n*5*pixel+(n-1)*tracking : 0;
}
export function vectorText(value,x,y,{pixel=7,color='#ffffff',tracking=2,align='start',maxWidth=Infinity,opacity=1}={}){
  const string=String(value??'').toUpperCase().replace(/[^A-Z0-9 $.\-:\/+%?!&]/g,'?');
  let width=vectorWidth(string,pixel,tracking);
  const fit=width>maxWidth?maxWidth/width:1;
  let origin=align==='middle'?x-width*fit/2:align==='end'?x-width*fit:x;
  const paths=[];
  for(const char of string){
    const d=glyphShape(char);
    if(d)paths.push('<path d="'+d+'" transform="translate('+origin.toFixed(2)+' '+y.toFixed(2)+') scale('+(pixel*fit).toFixed(5)+')" fill="'+color+'"/>');
    origin+=(5*pixel+tracking)*fit;
  }
  return '<g opacity="'+opacity+'">'+paths.join('')+'</g>';
}
